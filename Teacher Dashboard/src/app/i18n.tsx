export type TranslationKey = keyof typeof translations;

registerFromI18nTable(translations as Record<string, { fr: string; en: string }>);

interface LanguageContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TranslationKey) => string;
  tp: (key: TranslationKey, params: Record<string, string | number>) => string;
  /** Auto-translate plugin: French source string → active language. */
  auto: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue>({
  lang: "en",
  setLang: () => {},
  t: (key) => translations[key]?.en ?? key,
  tp: (key) => translations[key]?.en ?? key,
  auto: (text) => text,
});

function interpolate(
  text: string,
  params: Record<string, string | number>
): string {
  return Object.entries(params).reduce(
    (result, [key, value]) =>
      result.replace(new RegExp(`\\{${key}\\}`, "g"), String(value)),
    text
  );
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readPersistedLang);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    persistLang(next);
    document.documentElement.lang = next;
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  useEffect(() => {
    const onStorage = (event: StorageEvent) => {
      if (event.key !== LANG_STORAGE_KEY || !event.newValue) return;
      if (event.newValue === "fr" || event.newValue === "en") {
        setLangState(event.newValue);
        document.documentElement.lang = event.newValue;
      }
    };
    const onCustom = (event: Event) => {
      const detail = (event as CustomEvent<string>).detail;
      if (detail === "fr" || detail === "en") {
        setLangState(detail);
        document.documentElement.lang = detail;
      }
    };
    window.addEventListener("storage", onStorage);
    window.addEventListener("lecture-lang-change", onCustom);
    return () => {
      window.removeEventListener("storage", onStorage);
      window.removeEventListener("lecture-lang-change", onCustom);
    };
  }, []);

  const t = useCallback(
    (key: TranslationKey): string => translations[key]?.[lang] ?? key,
    [lang]
  );

  const tp = useCallback(
    (key: TranslationKey, params: Record<string, string | number>): string =>
      interpolate(translations[key]?.[lang] ?? key, params),
    [lang]
  );

  const auto = useCallback(
    (text: string): string => autoTranslate(text, lang),
    [lang]
  );

  const value = useMemo(
    () => ({ lang, setLang, t, tp, auto }),
    [lang, setLang, t, tp, auto]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
